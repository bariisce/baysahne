"""Markdown report for the content import (written to docs/CONTENT_IMPORT_REPORT.md)."""

from pathlib import Path


def write_report(rep, path: Path) -> None:
    lines: list[str] = []
    add = lines.append
    add("# Content Import Report — `BAY SAHNE BİLGİLER.docx`\n")
    add("_Generated by `python -m app.cli import-content`. Do not edit by hand; re-run the command._\n")
    add(f"- Run at: `{rep.started_at}`")
    add(f"- Source SHA-256: `{rep.source_sha256}`")
    add(f"- Records created: **{len(rep.created)}**; already present (left untouched): **{len(rep.skipped_existing)}**")
    add(f"- Media: **{rep.media_created}** stored, **{rep.media_reused}** reused (matched by SHA-256)")
    formats = ", ".join(f"{k} ×{v}" for k, v in sorted(rep.media_by_type.items()))
    add(f"- Real file formats detected: {formats}\n")

    add("## Productions\n")
    add("| Production | Result | Listed under “SAHNEDEKİ OYUNLAR” | Genre | Duration (source) | Poster "
        "| Photos (listed → imported) | Video |")
    add("|---|---|---|---|---|---|---|---|")
    for p in rep.productions:
        add(f"| {p['title']} | {p['result']} | {'yes' if p['on_stage'] else 'no'} | {', '.join(p['genres']) or '—'} "
            f"| {p['duration_text'] or '—'} | {p['poster'] or '—'} "
            f"| {p['gallery_in_source']} → {p['gallery_imported']} "
            f"| {'yes' if p['videos'] else '—'} |")
    add("\nCredits, in source order:\n")
    for p in rep.productions:
        add(f"- **{p['title']}**: " + "; ".join(p["credits"]))

    add("\n## Missing assets\n")
    if rep.missing_assets:
        add("Referenced in the document but not present in the supplied folder. Nothing was substituted; the app "
            "simply shows fewer photos. Staff can upload them later from the admin panel.\n")
        for m in rep.missing_assets:
            add(f"- {m['production']}: `{m['file']}`")
    else:
        add("None.")

    if rep.renamed_assets:
        add("\n## Found under a different extension\n")
        add("The document names these files with `.svg`, but they were supplied under their real image extension. "
            "They were matched by name and imported normally.\n")
        for referenced, found in rep.renamed_assets:
            add(f"- `{referenced}` → `{found}`")

    add("\n## File extension vs. real format\n")
    add(f"All {len(rep.extension_mismatch)} supplied `.svg` files are raster images, not SVG. The importer detects "
        "the real format from the file bytes and re-encodes every image: metadata is stripped and WebP variants "
        "(480 px and 1280 px wide) are generated. Files that are not JPEG:\n")
    for name, kind in rep.extension_mismatch:
        if kind != "JPEG":
            add(f"- `{name}` → {kind}")

    add("\n## Files not referenced by the document\n")
    for f in rep.unreferenced_assets:
        add(f"- `{f}`")
    if not rep.unreferenced_assets:
        add("None.")
    add("\n`baysahnelogo1.svg` (PNG, 5000×5000) is the same image served as the logo on baysahne.com and is used as "
        "the organisation logo. `baysahnelogo2.svg` (older hat-and-suit logo) was not imported.")

    add("\n## Fields absent from the source\n")
    add("Nothing was invented. The app hides a section when its data is missing.\n")
    for i in rep.incomplete:
        add(f"- **{i['production']}**: {', '.join(i['missing'])}")

    add("\n## Transformations applied\n")
    add("| Where | Before | After | Reason |")
    add("|---|---|---|---|")
    for t in rep.transforms:
        add(f"| {t['where']} | {t['before']} | {t['after']} | {t['reason']} |")

    add("\n## Source inconsistencies and notes\n")
    for n in rep.notes:
        add(f"- **{n['production']}**: {n['note']}")
    add("- **SAHNEDEKİ OYUNLAR**: the 5 productions after this heading are flagged `on_stage` (“Sahnede”). This is an "
        "editable label only; it is not treated as proof that they are currently running, and no dates were created.")
    add("- **Publication**: all productions were imported as `published` because they are the theatre's official "
        "repertoire (also public on baysahne.com). Staff can unpublish or archive any of them. The import never "
        "creates notification jobs.")
    add("- **Legal texts**: the 4 texts (privacy, terms, cookies, KVKK) were written for the website. They are "
        "imported verbatim as **drafts** and are not published. See `docs/LEGAL_REVIEW.md`.")
    add("- **Video link**: the Bir Yaz Gecesi Rüyası link is stored exactly as given (including its `?si=` parameter).")

    add("\n## Records created in this run\n")
    for c in rep.created or ["(none — everything already existed)"]:
        add(f"- {c}")
    if rep.skipped_existing:
        add("\n## Already present (not modified)\n")
        for c in rep.skipped_existing:
            add(f"- {c}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
